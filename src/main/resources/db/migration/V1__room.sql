-- Runs on Postgres (Neon) and on H2 in PostgreSQL mode, so it sticks to the syntax both speak.

create table boring_thing (
    id               bigint generated by default as identity primary key,
    original         varchar(140)  not null,
    twist_setting    integer       not null,
    twist_constraint integer       not null,
    twist_stakes     integer       not null,
    author           varchar(40)   not null,
    genre            varchar(20)   not null,
    hype             integer       not null default 0,
    rerolls          integer       not null default 0,
    peak_tier        varchar(20)   not null,
    lore             varchar(2000) not null default '',
    created_at       timestamp(6) with time zone not null,
    -- The submitter's private id; never leaves the server
    player_id        varchar(64)
);

-- The leaderboard query: top 50 by hype, newest first on ties
create index boring_thing_rank on boring_thing (hype desc, created_at desc);

create table player_progress (
    player_id      varchar(64) primary key,
    submits        integer      not null default 0,
    hypes          integer      not null default 0,
    rerolls        integer      not null default 0,
    self_hypes     integer      not null default 0,
    mythics        integer      not null default 0,
    mutator_hypes  integer      not null default 0,
    genres         varchar(200) not null default '',
    triggered_wave boolean      not null default false,
    night_owl      boolean      not null default false
);

create table player_achievement (
    player_id   varchar(64) not null references player_progress (player_id) on delete cascade,
    code        varchar(40) not null,
    unlocked_at timestamp(6) with time zone not null,
    primary key (player_id, code)
);

-- The one row every backend instance agrees on: the active mutator, whether a chaos wave is
-- armed, and who last ran the entropy tick
create table room_state (
    id              integer primary key,
    mutator         varchar(20),
    mutator_genre   varchar(20),
    mutator_ends_at timestamp(6) with time zone,
    wave_armed      boolean not null default true,
    decayed_at      timestamp(6) with time zone not null
);

insert into room_state (id, wave_armed, decayed_at)
values (1, true, timestamp with time zone '1970-01-01 00:00:00+00');

-- Transactional outbox: written in the same transaction as the change it describes, then
-- announced with NOTIFY (delivered by Postgres only on commit). Doubles as the chronicle log
-- and as the replay buffer for SSE clients that reconnect with Last-Event-ID.
create table chaos_event (
    id         bigint generated by default as identity primary key,
    type       varchar(20)    not null,
    -- {"de": …, "en": …}: the payload as each language reads it
    payload    varchar(16000) not null,
    created_at timestamp(6) with time zone not null
);

create index chaos_event_type on chaos_event (type, id);

-- How many SSE clients each running instance holds, so presence counts the whole room
create table relay_instance (
    instance_id varchar(64) primary key,
    online      integer not null,
    seen_at     timestamp(6) with time zone not null
);
